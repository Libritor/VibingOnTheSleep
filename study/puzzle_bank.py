# ------------------------------------------------------------------ the bank
def build(seed=2026):
    rng = random.Random(seed)
    arith = []
    for nums in itertools.combinations_with_replacement(range(1, 14), 4):
        for target, (whole, total, ex) in arith_solutions(nums, list(ARITH_TARGETS)).items():
            if total and whole <= 3:
                arith.append(dict(numbers=list(nums), target=target, tier="fraction" if whole == 0 else "rare"))
    # keep the bank a manageable size, both tiers, every target
    rng.shuffle(arith)
    keep, seen = [], {}
    for p in arith:
        k = (p["target"], p["tier"])
        if seen.get(k, 0) < 30:
            seen[k] = seen.get(k, 0) + 1
            keep.append(p)
    table = resistor_table(7)
    res = [dict(target=f"{v.numerator}/{v.denominator}", count=n)
           for v, (n, _) in table.items()
           if n in (5, 6, 7) and v.numerator > 1 and v.denominator > 1 and Fraction(1, 4) <= v <= 4]
    rng.shuffle(res)
    res = [p for p in res if p["count"] < 7] + [p for p in res if p["count"] == 7][:64]   # 7s are hard
    ana = []
    for w in words():
        ana.append(dict(letters=scramble(w, rng), answer_sha256=word_hash(w)))
    rng.shuffle(ana)
    bank = []
    for fam, items, tag in (("arith", keep, "A"), ("resistor", res, "R"), ("anagram", ana, "W")):
        rng.shuffle(items)
        for i, p in enumerate(items):
            bank.append(dict(id=f"{tag}{i + 1:03d}", family=fam, **p))
    return bank


def load():
    return json.loads(BANK.read_text())["puzzles"]


def selfcheck(bank):
    """Every puzzle is solvable and its checker accepts a solution and refuses a wrong answer."""
    table = resistor_table(7)
    inv = {f"{v.numerator}/{v.denominator}": e for v, (n, e) in table.items()}
    ws = {word_hash(w): w for w in words()}
    for p in bank:
        if p["family"] == "arith":
            whole, total, ex = arith_solutions(p["numbers"], p["target"])
            assert total and check(p, ex)[0], p
            assert not check(p, " + ".join(map(str, p["numbers"])))[0] or sum(p["numbers"]) == p["target"], p
        elif p["family"] == "resistor":
            assert table[Fraction(p["target"])][0] == p["count"], p
            assert check(p, inv[p["target"]])[0], p
            assert not check(p, "1+1")[0], p
        else:
            w = ws[p["answer_sha256"]]
            assert sorted(w) == sorted(p["letters"]) and check(p, w.lower())[0], p
            assert not check(p, p["letters"])[0], p
    return True


def main():
    bank = build()
    selfcheck(bank)
    BANK.parent.mkdir(parents=True, exist_ok=True)
    counts = {f: sum(p["family"] == f for p in bank) for f in FAMILIES}
    BANK.write_text(json.dumps(dict(version=1, seed=2026, counts=counts, puzzles=bank), indent=0))
    tiers = {}
    for p in bank:
        if p["family"] == "arith":
            tiers[(p["target"], p["tier"])] = tiers.get((p["target"], p["tier"]), 0) + 1
    print(f"wrote {BANK}: {counts}; arithmetic by target and tier {tiers}")
    print("every puzzle solvable, every checker accepts a solution and refuses a wrong answer")


if __name__ == "__main__":
    sys.exit(main())
